import asyncio
import json
import os
import re
import time
from typing import Any

import ollama

from app.config import get_settings
from app.utils.logger import logger

settings = get_settings()


class AIService:
    """Service for AI interactions using Ollama"""

    def __init__(self):
        self.model = settings.ollama_model
        self.client = ollama.AsyncClient()

    @staticmethod
    def _strip_thinking(text: str) -> str:
        """Remove Qwen3 <think>...</think> blocks from output."""
        return re.sub(r"<think>[\s\S]*?</think>", "", text).strip()

    async def generate_response(self, prompt: str, context: dict[str, Any] = None) -> str:
        """
        Generate AI response using Ollama
        """
        try:
            logger.log_thought("Constructing optimal search matrix and contextual parameters for query...")
            # Build the full prompt
            full_prompt = self._build_prompt(prompt, context)

            logger.log_action("Interrogating local AI models", target=self.model)
            # Call Ollama with streaming enabled (120s timeout for initial connection)
            stream = await asyncio.wait_for(
                self.client.generate(
                    model=self.model,
                    prompt=full_prompt,
                    stream=True,
                    options={
                        "temperature": 0.4,
                        "repeat_penalty": 1.15,
                        "top_p": 0.9,
                        "stop": ["End of Report", "Generated by AI"]
                    }
                ),
                timeout=120,
            )

            full_response = ""
            in_thinking = False
            deadline = time.monotonic() + 120  # 2-minute deadline for full stream
            logger.stream_start()  # Signal frontend: AI tokens incoming
            try:
                async for chunk in stream:
                    if time.monotonic() > deadline:
                        logger.log_warning("AI stream exceeded 120s deadline, truncating")
                        break
                    token = chunk.get('response', '')
                    if token:
                        full_response += token
                        # Filter out Qwen3 <think>...</think> blocks from stream
                        if "<think>" in token:
                            in_thinking = True
                        if not in_thinking:
                            logger.stream_token(token)
                        if "</think>" in token:
                            in_thinking = False
            except (ConnectionError, OSError, ollama.ResponseError, json.JSONDecodeError) as stream_err:
                logger.log_error(f"Stream interrupted: {str(stream_err)}")
            finally:
                logger.stream_end()  # Signal frontend: AI stream finished

            # Clean any thinking blocks from the final response
            full_response = self._strip_thinking(full_response)
            logger.log_success("Model response synthesized.")
            return full_response

        except (ConnectionError, OSError, ollama.ResponseError, ValueError) as e:
            logger.log_error(f"Core failure during model synthesis: {str(e)}")
            return f"JARVIS encountered an error: {str(e)}"

    def _build_prompt(self, query: str, context: dict[str, Any] = None) -> str:
        """Build comprehensive prompt for AI"""

        system_prompt = """You are J.A.R.V.I.S., an experienced open-source intelligence analyst writing an in-depth briefing about a person. Your job is to read all provided data carefully, figure out who this person really is, and write a thorough, insightful analysis. Do not rush — take the space you need to paint a complete picture.

TARGET: '{query}'

YOUR APPROACH:
Think like a seasoned analyst, not a database. Do not just list facts — explain what they mean and why they matter. When you see someone has 50 GitHub repos in Python and ML, don't just say "50 repos in Python" — explain what kind of developer they are, what their technical trajectory looks like, what projects stand out and why, and what this tells us about their career direction.

When you see activity on multiple platforms, analyze the patterns deeply: Are they consistent in how they present themselves across platforms? Do the locations match? Does the professional timeline make sense? Is there a gap in activity that might indicate a career change, relocation, or period of inactivity?

Connect information across sources and draw meaningful conclusions. If GitHub says they are in Istanbul and LinkedIn says Berlin, discuss what that might mean. If their repos are all about AI but their job title says "marketing," explore that contradiction. Look for the story behind the data.

WRITING STYLE:
- Write in rich, detailed paragraphs. Each paragraph should be 3-5 sentences that develop an idea fully.
- Use bullet points only for listing specific accounts in Online Presence. Everything else should be flowing prose.
- Be direct and confident when data supports it. Be honest and specific about uncertainty when it does not.
- Sound like a knowledgeable colleague giving a thorough debrief — professional, analytical, and genuinely insightful.
- Do NOT use filler phrases like "Based on the available data" or "It is worth noting that" or "In conclusion" — just state your analysis directly.
- Vary your sentence structure. Mix short punchy statements with longer analytical observations.

STRUCTURE (use these exact markdown headers, skip any section that has zero data):

## Summary
Write 4-6 sentences providing a comprehensive overview: who this person is, their primary role and field, where they appear to be based, their most significant professional or online presence, and the single most important or interesting finding from the data. A reader should walk away from this section with a solid understanding of the target.

## Online Presence
List each confirmed account on its own line using this format:
- **Platform**: [username](URL) — key metrics, activity level, and notable observations

If the SOCIAL MEDIA context is split into "PRIMARY TARGET" and "SAME-NAME CANDIDATES" groups, list the PRIMARY TARGET accounts first. Then, under a separate subheading "**Same-name accounts (unverified — possibly different people):**", list the SAME-NAME CANDIDATE accounts and append [UNVERIFIED — possibly different person] to each. Do NOT describe these candidate accounts in any other section.

After the list, write a short paragraph analyzing their overall digital footprint: How many platforms are they active on? Is their presence consistent or fragmented? Do they use the same username/identity across platforms? What does their platform choice tell us about them?

Mark anything unverified with [UNVERIFIED]. Do not list platforms where you found no evidence.

## Professional Profile
Write 2-3 detailed paragraphs covering: current role and organization, career trajectory if visible, technical skills and areas of expertise, notable projects or achievements, professional reputation indicators, and any publications, patents, or academic work. Discuss not just what they do, but how they approach their work — what patterns emerge from their projects, contributions, or professional activity? What level of seniority or expertise does their body of work suggest?

## Behavioral Patterns
Write 2-3 paragraphs analyzing: their online activity patterns and frequency, the type of content they create or engage with, their communication style and tone across platforms, personality indicators that emerge from their digital behavior, location and timezone signals, and how they interact with their professional community. Consider what their behavior reveals about their priorities, interests, and professional relationships.

## Analyst Notes
Write a thorough assessment of 3-5 sentences covering: overall data confidence level (HIGH / MEDIUM / LOW) with specific justification for that rating, any inconsistencies or contradictions found between different sources, significant gaps in the available information, and recommendations for what additional data sources could fill those gaps.

STRICT RULES:
1. IDENTITY LOCK: The subject is ALWAYS '{query}'. Use the [CONFIRMED SUBJECT ANCHOR] block (when present) as ground truth for who the target is. This applies to EVERY source — web search and deep context included, not just social media. Web/deep results are frequently dominated by a more famous DIFFERENT person who shares part of the name (e.g. for a query 'Yigit Erdogan', results about 'Yigit Bulut' or about President 'Erdogan' are NOT the subject). Never adopt such a person as the subject, and never rename the subject to a different full name or surname than '{query}'. The SOCIAL MEDIA context may be pre-grouped into "PRIMARY TARGET" and "SAME-NAME CANDIDATES" sections; write Summary, Professional Profile, and Behavioral Patterns using ONLY the PRIMARY TARGET accounts plus GitHub/web/deep data that genuinely matches the anchor. Treat every SAME-NAME CANDIDATE and every differently-named web/deep entity as a DIFFERENT person: never attribute their job, location, bio, or activity to the target, and never blend their facts into the prose. When the anchor data is sparse and web/deep context is about other people, follow the SPARSE DATA PROTOCOL and report only the little that genuinely belongs to '{query}' — do NOT pad the report with a famous namesake. When unsure whether a fact belongs to the target, leave it out and note the ambiguity in Analyst Notes.
2. ZERO HALLUCINATION: Only report what the provided context directly supports. Do NOT invent accounts, relationships, work history, or biographical details. If you are unsure, say so explicitly rather than guessing. Academic publications, patents, and institutional records that match only by name are NOT proof of identity — do not present them as the subject's work unless the confirmed anchor (GitHub/social accounts) corroborates them; otherwise omit them or clearly mark them [UNVERIFIED].
3. SPARSE DATA PROTOCOL: If you have fewer than 5 concrete data points, write ONLY the Summary and Analyst Notes sections. Even with limited data, be thorough in analyzing what you do have. A detailed truthful report from limited data is always better than a fabricated comprehensive one.
4. TURKISH NAMES: Preserve Turkish characters exactly as they appear (ı, İ, ö, ü, ç, ş, ğ). Write your analysis in English but keep proper nouns in their original form.
5. LINKS: Format all URLs as clickable markdown links: [visible text](URL).
6. NO PADDING: Do not write introductions, conclusions, sign-offs, or "end of report" markers. Start directly with ## Summary and stop when your analysis is complete."""

        user_prompt = f"\n\nAnalyze this target: {query}"

        if context:
            context_str = "\n\n=== INTELLIGENCE CONTEXT ==="

            if context.get('anchor'):
                context_str += (
                    f"\n\n[CONFIRMED SUBJECT ANCHOR]\nThe subject is '{query}'. "
                    f"Verified identity signals: {context['anchor']}. "
                    "Any source below (web, deep context, or social) describing a person whose "
                    f"name does NOT match '{query}' is a DIFFERENT individual and unrelated noise — "
                    "never make them the subject and never rename the subject to theirs."
                )

            if context.get('github'):
                context_str += f"\n\n[GITHUB DATA]\n{context['github']}"

            if context.get('web_search'):
                context_str += (
                    "\n\n[WEB SEARCH] (may include unrelated namesakes — attribute only what matches the anchor)\n"
                    f"{context['web_search']}"
                )

            if context.get('social_media'):
                context_str += f"\n\n[SOCIAL MEDIA]\n{context['social_media']}"

            if context.get('deep_context'):
                context_str += (
                    "\n\n[DEEP CONTEXT] (may include unrelated namesakes — attribute only what matches the anchor)\n"
                    f"{context['deep_context']}"
                )

            user_prompt += context_str

        return system_prompt.replace('{query}', query) + user_prompt

    async def extract_profile_data(self, ai_response: str, query: str) -> dict[str, Any]:
        """
        Extract structured profile data from AI response
        """
        # Ask AI to structure the data
        extraction_prompt = f"""Based on this information about "{query}",
extract and return ONLY a JSON object with these fields:
- name: string (the subject is "{query}"; use this exact name or a directly-confirmed variant of it. NEVER return a different person's name — e.g. a more famous namesake or a differently-surnamed individual who only appeared in unrelated web/deep results)
- description: string (Write 2-3 detailed paragraphs that paint a complete picture of who this person is. First paragraph: Start with their full name, primary professional identity, and where they are based. Describe their current role, organization, and core area of expertise. Second paragraph: Discuss their most notable skills, projects, achievements, or professional contributions. Mention specific technologies, platforms, or fields they work in. If they have a visible career trajectory, describe it. Third paragraph: Analyze what makes this person distinctive — their online presence patterns, professional reputation indicators, or unique characteristics that emerge from the data. Write in third person, present tense. Do not use vague praise like "highly skilled" or "passionate" — instead state specific, concrete facts. Do not include information that is not in the source data. CRITICAL: Describe ONLY the single primary target. If the source data references multiple people who share this name (e.g. accounts grouped as same-name candidates, or conflicting professions/locations), use ONLY facts about the primary target and never blend a namesake's job, employer, or location into this description. When a fact's owner is uncertain, omit it. Example tone: "Ahmet Yilmaz is a backend engineer based in Istanbul, currently working at Trendyol where he focuses on the platform's microservices infrastructure. With over 6 years of professional experience visible through his LinkedIn profile, he has built a career centered around distributed systems and cloud-native architectures. His GitHub profile reveals 47 public repositories, predominantly in Go and Python, with notable contributions to several open-source service mesh projects.")
- similar_profiles: array of strings (names or handles of same-name people who appear in the data but are likely DIFFERENT individuals from the target — capture them here instead of merging them into the description)
- estimated_location: string (guessed country)
- capital_city: string (capital of that country)
- social_media_score: integer (0-100, estimate based on number of linked accounts and recency of posts/activity)
- last_activity_summary: string (brief 2-4 word summary of when they were last active, e.g., "Active today", "Active last week", "No recent activity")
- cross_validation_issues: array of strings (Identify any significant inconsistencies across different data sources. E.g., 'GitHub location is Turkey but LinkedIn says USA' or 'Web results indicate doctor, GitHub indicates programmer'. If all sources match and refer to the same person, return an empty array [])
- network_connections: array of objects [{{"name": "Name of connection", "role": "Their job/title", "relation": "How they are related (e.g. Co-founder, Co-author, Co-star, Director, Producer, Collaborator, Colleague)"}}] (Extract ALL verifiable relationships from context: co-workers, co-stars, directors, producers, collaborators, academic/business partners, frequently mentioned associates. Include relationships found in Turkish-language or non-English sources. Max 15 people. Return [] only if truly no relationships are found.)
- email_addresses: array of strings (Extract any email addresses found in the context. E.g. found in GitHub bio or web results. If none, return [])

Previous Information:
{ai_response}

Return ONLY valid JSON, no other text."""

        try:
            logger.log_thought("Attempting to parse bio-data and network nodes from unstructured text...")
            response = await asyncio.wait_for(
                self.client.generate(
                    model=self.model,
                    prompt=extraction_prompt,
                    options={
                        "temperature": 0.1,
                        "top_p": 0.1
                    }
                ),
                timeout=60,
            )

            response_text = self._strip_thinking(response['response'])

            # Find JSON in response
            start_idx = response_text.find('{')
            end_idx = response_text.rfind('}') + 1

            if start_idx != -1 and end_idx > start_idx:
                json_str = response_text[start_idx:end_idx]
                parsed_data = json.loads(json_str)
                logger.log_success("Bio-data nodes successfully extracted.")
                return parsed_data

            # Fallback
            logger.log_warning("Failed to locate clean JSON structure. Initiating fallback protocol.")
            return {
                "name": query,
                "description": ai_response[:500],
                "similar_profiles": [],
                "cross_validation_issues": [],
                "network_connections": [],
                "email_addresses": []
            }

        except (json.JSONDecodeError, ValueError, KeyError, AttributeError) as e:
            logger.log_error(f"Data extraction node failed: {e}")
            return {
                "name": query,
                "description": ai_response[:500] if ai_response else "",
                "similar_profiles": [],
                "cross_validation_issues": [],
                "network_connections": [],
                "email_addresses": []
            }

    async def chat_with_context(self, query_name: str, messages: list, user_context: str = ""):
        """
        RAG Chat generator — ChromaDB semantic search primary, JSON fallback supported.
        Injects user memory context for personalized responses.
        Yields tokens for StreamingResponse.
        """
        # Use the most recent user message as the embedding query
        last_user_message = ""
        for msg in reversed(messages):
            role = msg.role if hasattr(msg, "role") else msg.get("role", "")
            if role == "user":
                last_user_message = msg.content if hasattr(msg, "content") else msg.get("content", "")
                break

        search_query = last_user_message or query_name

        # Load RAG context from JSON file
        context_text = ""
        context_source = "none"
        safe_filename = re.sub(r"[^a-zA-Z0-9_\-]", "_", query_name.lower())
        context_path = f"data/contexts/{safe_filename}.json"

        if os.path.exists(context_path):
            try:
                with open(context_path, encoding="utf-8") as f:
                    data = json.load(f)

                if data.get("github"):
                    context_text += "GITHUB PROFILE DATA:\n" + data["github"] + "\n\n"
                if data.get("social_media"):
                    context_text += data["social_media"] + "\n\n"

                deep_ctx = data.get("deep_context", "")
                if len(deep_ctx) > 12000:
                    deep_ctx = deep_ctx[:12000] + "... [TRUNCATED DUE TO CONTEXT LIMIT]"
                context_text += "WEB SEARCH DEEP CONTEXT:\n" + deep_ctx
                context_source = "json"
                logger.log_action(
                    f"RAG context loaded from JSON knowledge base: {query_name}"
                )
            except (OSError, json.JSONDecodeError, KeyError, ValueError) as e:
                logger.log_warning(f"Failed to load JSON context: {e}")
                context_text = "ERROR: Context file could not be read."
        else:
            context_text = (
                "ERROR: No intelligence data found for this query. "
                "Please run a search first."
            )

        source_label = "JSON CONTEXT"

        # 2. Sistem prompt
        user_memory_block = ""
        if user_context:
            user_memory_block = f"""

=== USER MEMORY (Personalization) ===
You remember the following about the user you are speaking with:
{user_context}
Use this knowledge to personalize your responses, address them by name if known, and adapt your communication style.
====================================="""

        system_prompt = f"""You are J.A.R.V.I.S., an advanced AI interacting with the user about a target entity named '{query_name}'.
You must answer the user's questions based EXCLUSIVELY on the gathered intelligence context below.
Context was retrieved via: {source_label}
CRITICAL RULES:
1. DO NOT HALLUCINATE OR GUESS. If the context does not contain the answer, say "I do not have sufficient data in the current intelligence context to answer this."
2. DO NOT USE EXTERNAL KNOWLEDGE. Only use the text provided.
3. Keep answers concise, highly analytical, and direct. Use J.A.R.V.I.S. persona (professional, objective).
{user_memory_block}
=== J.A.R.V.I.S INTELLIGENCE CONTEXT ===
{context_text}
========================================"""

        # Format messages for Ollama Chat API
        formatted_messages = [
            {"role": "system", "content": system_prompt}
        ]

        # Add user history
        for msg in messages:
            # Handle Pydantic model vs dict
            role = msg.role if hasattr(msg, 'role') else msg['role']
            content = msg.content if hasattr(msg, 'content') else msg['content']
            formatted_messages.append({"role": role, "content": content})

        # 3. Stream response (60s timeout for initial connection)
        try:
            response = await asyncio.wait_for(
                self.client.chat(
                    model=self.model,
                    messages=formatted_messages,
                    stream=True,
                    options={
                        "temperature": 0.2, # Very low temp to prevent hallucination in facts
                        "top_p": 0.5,
                        "repeat_penalty": 1.1
                    }
                ),
                timeout=60,
            )

            in_thinking = False
            async for chunk in response:
                if 'message' in chunk and 'content' in chunk['message']:
                    token = chunk['message']['content']
                    # Filter out Qwen3 <think>...</think> blocks
                    if "<think>" in token:
                        in_thinking = True
                    if not in_thinking:
                        yield token
                    if "</think>" in token:
                        in_thinking = False

        except (ConnectionError, OSError, ollama.ResponseError, json.JSONDecodeError, ValueError) as e:
            logger.log_error(f"Chatbot neural link failed: {e}")
            yield f"\n\n[SYSTEM ERROR: Neural reasoning engine failure. Details: {e}]"

    async def analyze_sentiment(self, text_context: str) -> dict:
        """
        Takes raw scraped text and performs a psychological/sentiment analysis using Ollama.
        Returns a specific JSON structure with pos/neu/neg percentages and dominant emotion.
        """
        if not text_context or len(text_context.strip()) < 50:
            return {
                "positive": 33,
                "neutral": 34,
                "negative": 33,
                "dominant_emotion": "INSUFFICIENT DATA",
                "summary": "Insufficient data."
            }

        # Protect context window limit
        if len(text_context) > 10000:
            text_context = text_context[:10000]

        sentiment_prompt = f"""You are J.A.R.V.I.S., analyzing the psychological profile and public sentiment of an entity based on the following scraped text data.
Analyze the overall tone, sentiment, and emotion present in the text.
You MUST respond IN ENGLISH.
You MUST output ONLY a valid JSON object without any markdown formatting or extra text.

Required JSON Structure:
{{
  "positive": <integer 0-100 representing positive sentiment percentage>,
  "neutral": <integer 0-100 representing neutral sentiment percentage>,
  "negative": <integer 0-100 representing negative sentiment percentage>,
  "dominant_emotion": "<string, one or two words describing the main emotion, e.g., 'Angry', 'Professional', 'Cheerful', 'Aggressive'>",
  "summary": "<string, 1 short sentence summarizing the public perception>"
}}

CRITICAL: The sum of positive + neutral + negative MUST exactly equal 100.
Do NOT include ```json tags.

TEXT TO ANALYZE:
{text_context}
"""

        try:
            response = await asyncio.wait_for(
                self.client.generate(
                    model=self.model,
                    prompt=sentiment_prompt,
                    options={
                        "temperature": 0.1,
                        "top_p": 0.1
                    }
                ),
                timeout=60,
            )

            response_text = self._strip_thinking(response['response'])

            # Extract JSON
            start_idx = response_text.find('{')
            end_idx = response_text.rfind('}') + 1

            if start_idx != -1 and end_idx > start_idx:
                json_str = response_text[start_idx:end_idx]
                parsed_data = json.loads(json_str)

                # Sanity check percentages
                pos = int(parsed_data.get('positive', 33))
                neu = int(parsed_data.get('neutral', 34))
                neg = int(parsed_data.get('negative', 33))

                total = pos + neu + neg
                if total == 0:
                    pos, neu, neg = 33, 34, 33
                elif total != 100:
                    # Normalize
                    pos = int((pos / total) * 100)
                    neu = int((neu / total) * 100)
                    neg = 100 - (pos + neu)

                return {
                    "positive": pos,
                    "neutral": neu,
                    "negative": neg,
                    "dominant_emotion": parsed_data.get('dominant_emotion', 'UNKNOWN').upper(),
                    "summary": parsed_data.get('summary', 'Analysis could not be completed.')
                }

        except (ConnectionError, OSError, ollama.ResponseError, json.JSONDecodeError, ValueError, KeyError) as e:
            logger.log_error(f"Sentiment analysis matrix failure: {e}")

        return {
            "positive": 33,
            "neutral": 34,
            "negative": 33,
            "dominant_emotion": "ERROR",
            "summary": "Analysis module crashed."
        }
